/**
 * Phase 15 — app-wide bilingual strings (English / Hinglish).
 *
 * Phase 13's language system (src/lib/language.ts) only covered
 * Login → Onboarding. Every other screen hardcoded Hinglish, so
 * picking English changed nothing past the login screen. This file
 * is the fix: ONE dictionary for every user-facing string on the
 * logged-in screens, keyed the same in both languages.
 *
 * Design:
 * - `en` is the typed source of truth; `hi` is annotated
 *   `: Strings`, so the compiler rejects a missing, extra or
 *   mistyped key in either language. Parameterised strings are
 *   functions, so both languages take the same arguments.
 * - Screens take a `language: AppLanguage` prop (from App state)
 *   and read `const s = stringsFor(language)` at the top. Changing
 *   the language in Profile re-renders the whole app — no reload.
 * - DO NOT translate (kept as content, never in this file): Quran
 *   Arabic text, verified dua Arabic text, dua / Quran Hinglish
 *   tarjuma content, proper names, numbers and dates.
 * - Login → Onboarding stay bilingual (both lines shown) via
 *   language.ts — this dictionary is NOT used there.
 * - The `hi` values are the existing copy verbatim wherever the
 *   string already existed; the `en` values are translations in
 *   the same short, direct, friendly voice. Nothing here invents
 *   a feature, a verse or a claim.
 */

