export const STRINGS: Record<AppLanguage, Strings> = { en, hi };

/** The dictionary for the given language. */
export function stringsFor(language: AppLanguage): Strings {
  return STRINGS[language];
}

/** Challenge category label (e.g. 'prayers' → 'Prayers' / 'Namaz'). */
export function challengeCategoryLabel(category: ChallengeCategory, language: AppLanguage): string {
  return stringsFor(language).challenges.categories[category];
}

/** What completes one day of a challenge in this category. Falls back to self-reported. */
export function challengeRequirement(category: ChallengeCategory, language: AppLanguage): string {
  const req = stringsFor(language).challenges.requirement;
  return req[category] ?? req.default;
}

/** Where a completed challenge day came from (server `source` value). */
export function challengeProgressSource(source: string, language: AppLanguage): string {
  return stringsFor(language).challenges.progressSource[source] ?? source;
}

/** Notification category label (e.g. 'prayer' → 'Prayer' / 'Namaz'). */
export function notificationTypeLabel(type: NotificationType, language: AppLanguage): string {
  return stringsFor(language).notificationSettings.typeLabels[type];
}

/** Points-history reason label (server `reason` value). */
export function pointReasonLabel(reason: PointTransaction['reason'], language: AppLanguage): string {
  return stringsFor(language).analytics.pointReason[reason];
}

/**
 * "45 min" under an hour, "1.5 gh" / "1.5 h" above it. Used by the
 * Focus KPIs and the Analytics bars (same rule in both places).
 */
export function minutesOrHours(totalMinutes: number, language: AppLanguage): string {
  if (totalMinutes < 60) return `${totalMinutes} min`;
  const hours = totalMinutes / 60;
  const label = Number.isInteger(hours) ? String(hours) : hours.toFixed(1);
  return `${label} ${language === 'hi' ? 'gh' : 'h'}`;
}
